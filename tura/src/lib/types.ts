export type Season = "spring" | "summer" | "autumn" | "winter";

export interface Coordinates {
  lat: number;
  lng: number;
}

/**
 * A catalogue adventure. `ref` is the human-facing reference number shown in
 * calendar entries, the journal and the adventure book.
 */
export interface Adventure {
  id: string;
  /** e.g. "TURA-014" — stable, shown throughout the app. */
  ref: string;
  title: string;
  /** Nearest recognisable place, e.g. "Wasdale Head, Cumbria". */
  location: string;
  /** National park, coastline or range this belongs to. */
  region: string;
  country: string;
  /** true for the 75% of the catalogue that sits inside the UK. */
  uk: boolean;
  coords: Coordinates;
  categories: Category[];
  /** 0 = day trip, 1 = overnight, 2 = the two-night escape. */
  nights: number;
  /** Two adults only, no company, no interruptions. */
  adultsOnly: boolean;
  /** 1–100. Drives the "next 15 by popularity" ranking. */
  popularity: number;
  /** Realistic all-in cost for two adults, in GBP. */
  estimatedCost: number;
  difficulty: Difficulty;
  bestSeasons: Season[];
  /** Suggested tier, based on cost and how far away it is. */
  tier: Tier;
  /** Driving time from central England, in hours. */
  travelHours: number;
  summary: string;
  /** What actually makes this worth the drive. */
  highlights: string[];
  /** Adventure-specific kit, on top of the standard list. */
  kit: string[];
}

/** Per-adventure state the couple owns. */
export interface AdventureRecord {
  adventureId: string;
  status: Status;
  /** Checklist item ids that have been ticked. */
  checked: string[];
  notes: string;
  /** ISO date the couple marked it completed. */
  completedOn?: string;
  favourite: boolean;
  updatedAt: string;
}

/** A dated slot generated by the calendar rules, optionally filled. */
export interface CalendarSlot {
  /** Deterministic id, e.g. "green-2026-03". */
  id: string;
  /** ISO yyyy-mm-dd — always a Saturday. */
  date: string;
  tier: Tier;
  /** Target spend for the tier, in GBP. */
  budget: number;
  /** Assigned adventure, if the couple has picked one. */
  adventureId?: string;
  /** Overrides the tier budget when the couple sets their own number. */
  budgetOverride?: number;
  note?: string;
}

