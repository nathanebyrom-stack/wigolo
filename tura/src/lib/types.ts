export interface Expense {
  id: string;
  slotId: string;
  adventureId?: string;
  label: string;
  amount: number;
  category: ExpenseCategory;
  date: string;
  createdAt: string;
}

export interface JournalEntry {
  id: string;
  adventureId: string;
  slotId?: string;
  /** ISO date the adventure happened. */
  date: string;
  title: string;
  body: string;
  /** 1–5. */
  rating: number;
  /** Free-text conditions, e.g. "Horizontal rain, then a clear dusk". */
  weather: string;
  /** Data URLs, downscaled on import to stay inside the storage budget. */
  photos: string[];
  /** Short quotable line pulled out for the adventure book. */
  standout: string;
  createdAt: string;
}

export interface Settings {
  /** Names of the two adults, used through the app. */
  partnerOne: string;
  partnerTwo: string;
  /** ISO yyyy-mm-dd. Drives the red birthday adventure each year. */
  birthday: string;
  /** Home point — distances and travel estimates are measured from here. */
  home: Coordinates;
  homeLabel: string;
  /** Which month the amber (every-other-month) rhythm starts on: 0 = Jan. */
  amberAnchorMonth: number;
  currency: string;
  theme: "dark" | "light" | "system";
  mapStyle: MapStyleId;
  onboarded: boolean;
}

export type MapStyleId = "terrain" | "satellite" | "outdoors";

/** The whole persisted state, versioned so migrations stay possible. */
export interface TuraState {
  version: number;
  settings: Settings;
  records: Record<string, AdventureRecord>;
  slots: Record<string, CalendarSlot>;
  expenses: Expense[];
  journal: JournalEntry[];
  /** Roulette results, newest first — keeps the wheel honest. */
  spins: { adventureId: string; at: string }[];
}
